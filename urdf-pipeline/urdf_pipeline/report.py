"""Plain-English output: the `check` summary and the REPORT.md written by `prepare`.

Console text uses ASCII tags only ([OK]/[WARN]/[FAIL]/[INFO]) so it displays correctly
in any Windows console.
"""

from __future__ import annotations

from pathlib import PurePosixPath

from .config import Config, UNITY_LINK_LIMIT
from .pipeline import CheckResult

INDENT = "         "


def _name(uri: str) -> str:
    return PurePosixPath(uri.replace("\\", "/")).name


def _list(items: list[str], limit: int = 10) -> list[str]:
    lines = [f"{INDENT}- {item}" for item in items[:limit]]
    if len(items) > limit:
        lines.append(f"{INDENT}- ... and {len(items) - limit} more")
    return lines


def render_check(result: CheckResult, config: Config) -> list[str]:
    lines = [f'URDF check: {result.file}  (robot "{result.robot}")', ""]

    if result.problems:
        lines.append(f"[FAIL] Structure: {len(result.problems)} problem(s) found:")
        lines += _list(result.problems, limit=50)
    else:
        lines.append(f"[OK]   Structure: {result.links} links, {result.joints} joints, one root link '{result.roots[0]}'.")
    if result.joint_types:
        lines.append("[INFO] Joint types: " + ", ".join(f"{n} {t}" for t, n in result.joint_types.items()) + ".")

    if result.meshes_total == 0:
        lines.append("[INFO] Meshes: none (the robot uses only simple shapes).")
    elif result.missing_meshes:
        lines.append(f"[FAIL] Meshes: {len(result.missing_meshes)} of {result.meshes_total} not found:")
        lines += _list(result.missing_meshes)
        lines.append(f"{INDENT}Fix: put the mesh folders next to the .urdf, or use --mesh-root FOLDER.")
    else:
        lines.append(f"[OK]   Meshes: {result.meshes_total} referenced, all found.")
    if result.absolute_meshes:
        lines.append(f"[WARN] {len(result.absolute_meshes)} mesh path(s) are absolute; they will only work on this computer:")
        lines += _list(result.absolute_meshes, limit=5)
    if result.unplaceable_meshes:
        lines.append(f"[WARN] {len(result.unplaceable_meshes)} mesh path(s) point outside the URDF's folder ('..'); "
                     "they can't be copied into the output folder:")
        lines += _list(result.unplaceable_meshes, limit=5)
    if result.non_stl_meshes:
        lines.append(f"[INFO] {len(result.non_stl_meshes)} mesh(es) are not STL (e.g. {_name(result.non_stl_meshes[0])}); "
                     "they are copied as-is.")
    if result.heavy_meshes:
        uri, tris = result.heavy_meshes[0]
        lines.append(f"[INFO] {len(result.heavy_meshes)} mesh(es) have more than 65,535 vertices "
                     f"(largest: {_name(uri)}, {tris:,} triangles).")
        lines.append(f"{INDENT}Unity's URDF Importer splits these automatically, but very detailed meshes can make Unity slow.")

    if not result.problems:
        budget = f"{result.links} links; limit {config.max_links} (Unity's hard limit is {UNITY_LINK_LIMIT})"
        if result.links <= config.max_links:
            lines.append(f"[OK]   Link budget: {budget}.")
        else:
            lines.append(f"[WARN] Link budget: {budget} - over the limit.")
            if result.will_collapse:
                lines.append(f"{INDENT}prepare will remove {result.links - result.links_after} frame-only links "
                             f"-> {result.links_after} links.")
            if result.parts > 1:
                lines.append(f"{INDENT}prepare will split the robot into {result.parts} parts.")
        if result.frame_only:
            lines.append(f"[INFO] {result.frame_only} link(s) are pure coordinate frames (no shape, no mass).")

    lines.append("")
    if result.ok:
        lines.append('Result: READY. Run "prepare" to build a Unity-ready folder.')
    else:
        lines.append("Result: NOT READY. Fix the [FAIL] items above, then run check again.")
    return lines


def render_prepare_report(manifest: dict) -> str:
    stats = manifest["stats"]
    source = manifest["source"]
    outputs = manifest["outputs"]
    out = [
        f"# Unity import report: {source['robot_name']}",
        "",
        f"Generated by urdf_pipeline {manifest['tool_version']} from `{PurePosixPath(source['file'].replace(chr(92), '/')).name}`.",
        "",
        "## Summary",
        "",
        "| | Before | After |",
        "| --- | --- | --- |",
        f"| Links in physics tree | {stats['links_in']} | {stats['links_out']} |",
        f"| URDF files | 1 | {stats['parts']} |",
        f"| Frame-only links moved to manifest | - | {stats['frames_collapsed']} |",
        f"| Meshes split into chunks | - | {stats['meshes_split']} ({stats['mesh_chunks_written']} chunk files) |",
        f"| Mesh files copied | - | {stats['mesh_files_copied']} |",
        "",
        "Self-check passed: rebuilding the robot from this folder gives back the original URDF exactly.",
        "",
        "## Import into Unity",
        "",
        "1. Make sure the Unity project has the **URDF Importer** package installed.",
        "2. Copy this **whole folder** into the project's `Assets/` folder. Keep the structure: "
        "the mesh folders must stay next to the `.urdf` file.",
    ]
    if len(outputs) == 1:
        out.append(f"3. In the Project window, right-click `{outputs[0]}` and choose "
                   "**Import Robot from Selected URDF file**.")
    else:
        out.append("3. Import each part file the same way (right-click > **Import Robot from Selected URDF file**): "
                   + ", ".join(f"`{name}`" for name in outputs) + ".")
        out.append("4. The parts must then be connected using the `bridge_joints` in `manifest.json` "
                   "(the Unity helper script for this is not written yet).")
    out += [
        "",
        "Coordinates: the URDF and mesh files are left in ROS coordinates on purpose. "
        "The URDF Importer converts them to Unity's axes itself, so do not rotate the robot by hand.",
    ]
    if stats["frames_collapsed"]:
        out += [
            "",
            "## Coordinate frames removed from physics",
            "",
            f"{stats['frames_collapsed']} links had no shape and no mass (e.g. camera optical frames). They were "
            "left out of the URDF to stay under Unity's link limit and are listed in `manifest.json` under "
            "`collapsed_frames`, with positions already converted to Unity coordinates (`unity` blocks). "
            "The Unity helper script that re-creates them as empty GameObjects is not written yet.",
        ]
    if manifest["warnings"]:
        out += ["", "## Warnings", ""] + [f"- {w}" for w in manifest["warnings"]]
    out += [
        "",
        "## Files",
        "",
        "- " + "\n- ".join(f"`{name}`" for name in outputs),
        "- `manifest.json` - everything that was changed, used by `rebuild` and by Unity scripts",
        "- mesh folders - copied from the original robot description",
        "",
    ]
    return "\n".join(out)
